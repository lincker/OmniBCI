"""Control events and peer lifecycle operations owned by the server."""
from typing import Callable, Protocol

from omnibci.application.plugin_management.execution import PluginExecutionReceipt
from omnibci.shared.events import Event, EventType

STIMULATION_PEER = "stimulation"
ACTUATION_PEER = "actuation"


class CommandDispatcherPort(Protocol):
    @property
    def is_ready(self) -> bool: ...
    def is_command_ready(self, event_type: EventType) -> bool: ...
    def dispatch(self, event: Event) -> None: ...


class PeerHostPort(CommandDispatcherPort, Protocol):
    async def ensure_peer_ready(self, role: str, snapshot: dict) -> None: ...
    def ensure_peer_ready_sync(self, role: str, snapshot: dict) -> None: ...
    async def close_peer(self, role: str) -> None: ...
    def execution_receipt(self, role: str) -> PluginExecutionReceipt | None: ...
    def close_peer_sync(self, role: str) -> None: ...
    def cancel_unaccepted_peer(self, role: str) -> bool: ...
    def close_settled_peer(self, role: str, connection: object) -> bool: ...
    def is_peer_ready(self, role: str) -> bool: ...
    def is_peer_connected(self, role: str) -> bool: ...
    def peer_connection_token(self, role: str) -> object | None: ...
    def forward_to_peer(self, role: str, event: Event, session: str, connection: object,
                        eligible: Callable[[], bool]) -> None: ...
    def is_current_peer_channel(self, role: str, channel_id: str) -> bool: ...
    def node_operation_id(self, role: str) -> str | None: ...
    def subscribe(self, event_type: EventType, handler: Callable[[Event], None]) -> None: ...
