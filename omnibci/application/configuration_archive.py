"""Persistence port for immutable runtime inputs and application receipts."""
from typing import Protocol


class ConfigurationArchive(Protocol):
    def stage(self, revision: str, snapshot: dict, *, generation: str | None,
              context: str, session_id: str | None) -> str: ...

    def confirm(self, attempt_id: str, revision: str, *, generation: str,
                receipt: dict) -> None: ...

    def fail(self, attempt_id: str, error: str) -> None: ...

    def link_session(self, session_id: str, revision: str) -> None: ...

    def get(self, revision: str) -> dict | None: ...

    def get_for_session(self, session_id: str) -> list[dict]: ...
