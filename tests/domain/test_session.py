"""Tests for the BCISession aggregate and its domain-event lifecycle."""
from __future__ import annotations

import numpy as np
import pytest

from omnibci.domain.session import BCISession, SessionState
from omnibci.domain.classification import Classification
from omnibci.domain.epoch import Epoch
from omnibci.domain.events import SessionEnded, SessionStarted


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _epoch(event_id: int = 7, channels: int = 3, samples: int = 5) -> Epoch:
    return Epoch(
        data=np.ones((channels, samples)),
        event_id=event_id,
        sample_rate=1000,
        channel_count=channels,
    )


def _clf(target_id: int = 2, event_id: int = 7, confidence=0.9) -> Classification:
    return Classification(target_id=target_id, event_id=event_id, confidence=confidence)


# ---------------------------------------------------------------------------
# BCISession aggregate — state machine
# ---------------------------------------------------------------------------

class TestSessionStateMachine:
    def test_initial_state_is_idle(self):
        assert BCISession().state is SessionState.IDLE

    def test_start_transitions_to_running(self):
        s = BCISession()
        s.start()
        assert s.state is SessionState.RUNNING

    def test_cannot_start_twice(self):
        s = BCISession()
        s.start()
        with pytest.raises(RuntimeError):
            s.start()

    def test_end_transitions_to_ended(self):
        s = BCISession()
        s.start()
        s.end()
        assert s.state is SessionState.ENDED

    def test_cannot_end_before_start(self):
        with pytest.raises(RuntimeError):
            BCISession().end()

    def test_session_id_autogenerated_and_stable(self):
        s = BCISession()
        first = s.session_id
        assert isinstance(first, str) and first == s.session_id

    def test_explicit_session_id_preserved(self):
        assert BCISession(session_id="abc").session_id == "abc"


# ---------------------------------------------------------------------------
# BCISession aggregate — trial recording invariants
# ---------------------------------------------------------------------------

class TestTrialRecording:
    def test_record_trial_requires_running(self):
        s = BCISession()  # IDLE
        with pytest.raises(RuntimeError):
            s.record_trial(_epoch(), _clf())

    def test_event_id_mismatch_rejected(self):
        s = BCISession()
        s.start()
        with pytest.raises(ValueError):
            s.record_trial(_epoch(event_id=7), _clf(event_id=8))

    def test_trial_numbers_are_monotonic_from_one(self):
        s = BCISession()
        s.start()
        ev1 = s.record_trial(_epoch(event_id=1), _clf(event_id=1))
        ev2 = s.record_trial(_epoch(event_id=2), _clf(event_id=2))
        assert (ev1.trial_number, ev2.trial_number) == (1, 2)
        assert s.trial_count == 2

    def test_trials_returns_defensive_copy(self):
        s = BCISession()
        s.start()
        s.record_trial(_epoch(), _clf())
        copy_list = s.trials
        copy_list.clear()
        assert s.trial_count == 1  # internal list untouched

    def test_last_classification_none_before_trials(self):
        s = BCISession()
        s.start()
        assert s.last_classification() is None

    def test_last_classification_returns_latest(self):
        s = BCISession()
        s.start()
        s.record_trial(_epoch(event_id=1), _clf(target_id=5, event_id=1))
        last = s.last_classification()
        assert last.target_id == 5

    def test_accuracy_none_without_trials(self):
        s = BCISession()
        s.start()
        assert s.accuracy(lambda t: 0) is None

    def test_accuracy_computed_against_ground_truth(self):
        s = BCISession()
        s.start()
        s.record_trial(_epoch(event_id=1), _clf(target_id=1, event_id=1))
        s.record_trial(_epoch(event_id=2), _clf(target_id=9, event_id=2))
        # ground truth always 1 → first correct, second wrong → 0.5
        assert s.accuracy(lambda t: 1) == 0.5


# ---------------------------------------------------------------------------
# BCISession aggregate — domain event accumulation
# ---------------------------------------------------------------------------

class TestDomainEventSequence:
    def test_start_emits_session_started(self):
        s = BCISession(paradigm="classic40SSVEP")
        s.start()
        events = s.pop_events()
        assert len(events) == 1
        assert isinstance(events[0], SessionStarted)
        assert events[0].paradigm == "classic40SSVEP"

    def test_pop_events_drains_queue(self):
        s = BCISession()
        s.start()
        s.pop_events()
        assert s.pop_events() == []

    def test_full_lifecycle_event_order(self):
        s = BCISession()
        s.start()
        s.record_trial(_epoch(event_id=1), _clf(event_id=1))
        s.end()
        kinds = [type(e).__name__ for e in s.pop_events()]
        assert kinds == ["SessionStarted", "TrialCompleted", "SessionEnded"]

    def test_session_ended_carries_total_trials(self):
        s = BCISession()
        s.start()
        s.record_trial(_epoch(event_id=1), _clf(event_id=1))
        s.end()
        ended = [e for e in s.pop_events() if isinstance(e, SessionEnded)][0]
        assert ended.total_trials == 1


# ---------------------------------------------------------------------------
# P1-6: the aggregate does not retain signal data (unbounded-memory fix)
# ---------------------------------------------------------------------------

class TestTrialsDoNotRetainSignal:
    def test_trial_stores_epoch_info_not_epoch(self):
        from omnibci.domain.epoch import EpochInfo
        s = BCISession()
        s.start()
        s.record_trial(_epoch(event_id=1), _clf(event_id=1))
        trial = s.trials[0]
        assert isinstance(trial.epoch_info, EpochInfo)
        assert not hasattr(trial, "epoch")
        # The metadata projection remains complete.
        assert trial.epoch_info.event_id == 1
        assert trial.epoch_info.duration_samples > 0

    def test_signal_array_is_released_after_record_trial(self):
        """Signal data can be collected once record_trial returns."""
        import gc
        import weakref

        s = BCISession()
        s.start()
        epoch = _epoch(event_id=1)
        ref = weakref.ref(epoch.data)
        s.record_trial(epoch, _clf(event_id=1))
        s.pop_events()
        del epoch
        gc.collect()
        assert ref() is None    # neither the aggregate nor its events retain data
