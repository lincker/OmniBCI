class TestTrialRecording:
    def test_record_trial_requires_running(self):
        s = BCISession()  # IDLE
        with pytest.raises(RuntimeError):
            s.record_trial(_epoch(), _clf())

    def test_event_id_mismatch_rejected(self):
        s = BCISession()
        s.start()
        with pytest.raises(ValueError):
            s.record_trial(_epoch(event_id=7), _clf(event_id=8))

    def test_trial_numbers_are_monotonic_from_one(self):
        s = BCISession()
        s.start()
        ev1 = s.record_trial(_epoch(event_id=1), _clf(event_id=1))
        ev2 = s.record_trial(_epoch(event_id=2), _clf(event_id=2))
        assert (ev1.trial_number, ev2.trial_number) == (1, 2)
        assert s.trial_count == 2

    def test_trials_returns_defensive_copy(self):
        s = BCISession()
        s.start()
        s.record_trial(_epoch(), _clf())
        copy_list = s.trials
        copy_list.clear()
        assert s.trial_count == 1  # internal list untouched

    def test_last_classification_none_before_trials(self):
        s = BCISession()
        s.start()
        assert s.last_classification() is None

    def test_last_classification_returns_latest(self):
        s = BCISession()
        s.start()
        s.record_trial(_epoch(event_id=1), _clf(target_id=5, event_id=1))
        last = s.last_classification()
        assert last.target_id == 5

    def test_accuracy_none_without_trials(self):
        s = BCISession()
        s.start()
        assert s.accuracy(lambda t: 0) is None

    def test_accuracy_computed_against_ground_truth(self):
        s = BCISession()
        s.start()
        s.record_trial(_epoch(event_id=1), _clf(target_id=1, event_id=1))
        s.record_trial(_epoch(event_id=2), _clf(target_id=9, event_id=2))
        # ground truth always 1 → first correct, second wrong → 0.5
        assert s.accuracy(lambda t: 1) == 0.5


